require('dotenv').config();
const { PrismaClient } = require('@prisma/client');
const { Pool } = require('pg');
const { PrismaPg } = require('@prisma/adapter-pg');
const crypto = require('crypto');

const rawUrl = process.env.DATABASE_URL || "";
const cleanUrl = rawUrl.split('?')[0];
const pool = new Pool({ connectionString: cleanUrl });
const adapter = new PrismaPg(pool);
const prisma = new PrismaClient({ adapter });

// Simple UUID v4 format check
const UUID_REGEX = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * POST /api/scolarite/documents-officiels/:id/sign
 *
 * Cryptographically "signs" an official document generated by the administration.
 * Generates a SHA-256 hash using the document details, timestamp, and staff ID.
 */
const signOfficialDocument = async (req, res) => {
  try {
    const { id } = req.params;
    const { id_staff } = req.body; // Optional: ID of the staff member signing

    // --- Validation ---
    if (!id || !UUID_REGEX.test(id)) {
      return res.status(400).json({
        success: false,
        message: `L'identifiant fourni ("${id}") n'est pas un UUID valide.`,
      });
    }

    // 1. Fetch the document from the new `document_officiel` table
    const document = await prisma.document_officiel.findUnique({
      where: { id_document_officiel: id },
    });

    if (!document) {
      return res.status(404).json({
        success: false,
        message: `Aucun document officiel trouvé avec l'id "${id}".`,
      });
    }

    // 2. Prevent double-signing
    if (document.hash) {
      return res.status(400).json({
        success: false,
        message: 'Ce document est déjà signé.',
      });
    }

    // 3. Generate Cryptographic Signature (SHA-256)
    // We combine unique document traits + timestamp + staff identity to create the seal
    const timestamp = new Date().toISOString();
    const staffIdentifier = id_staff || 'SYSTEM_ADMIN';
    const dataToHash = `${document.id_document_officiel}-${document.nom}-${timestamp}-${staffIdentifier}`;

    const generatedHash = crypto
      .createHash('sha256')
      .update(dataToHash)
      .digest('hex');

    // 4. Update the database record
    const updatedDocument = await prisma.document_officiel.update({
      where: { id_document_officiel: id },
      data: { hash: generatedHash },
    });

    // CRITICAL: We must remove the `contenu` (BYTEA buffer) from the returned object.
    // Sending a massive binary buffer inside a JSON response will cause severe performance issues.
    const { contenu, ...documentWithoutBuffer } = updatedDocument;

    return res.status(200).json({
      success: true,
      message: 'Document officiel signé avec succès.',
      data: documentWithoutBuffer,
    });
  } catch (error) {
    console.error('[Signature Électronique] Error:', error);
    return res.status(500).json({
      success: false,
      message: 'Une erreur est survenue lors de la signature du document.',
    });
  }
};

module.exports = {
  signOfficialDocument,
};